"""Generate documentation from the rule registry, so docs cannot drift from code.

``docs/RULES.md`` is the output of ``aiak rules --format md``. The checks table in
``docs/CROSSWALK.md`` is the output of ``aiak rules --format crosswalk``. Tests fail if either
file is out of date.
"""

from __future__ import annotations

from ai_assurance_kit.checks import all_rules
from ai_assurance_kit.checks.engine import Rule

CROSSWALK_BEGIN = "<!-- BEGIN GENERATED: aiak rules --format crosswalk -->"
CROSSWALK_END = "<!-- END GENERATED -->"


def _refs(rule: Rule, source: str) -> list[str]:
    return [r.pointer for r in rule.refs if r.source == source]


def rules_markdown() -> str:
    lines = [
        "# Checks reference",
        "",
        "<!-- Generated by `aiak rules --format md`. Do not edit by hand. -->",
        "",
        "Every check is a prompt for human judgement, not a verdict. Severity says how soon a",
        "human answer is needed:",
        "",
        "- **high**: resolve, or explicitly accept with a named owner, before relying on the use;",
        "- **warning**: needs a recorded human decision before the next lifecycle stage;",
        "- **info**: worth recording; no action required to proceed.",
        "",
        "A citation means the source makes the prompt worth asking. It does not mean the source",
        "requires what the check looks for. Unofficial; not government guidance.",
        "",
        "| ID | Severity | Check |",
        "|---|---|---|",
    ]
    rules = all_rules()
    lines += [f"| [{r.id}](#{r.id.lower()}) | {r.severity.value} | {r.title} |" for r in rules]
    for r in rules:
        skipped = ", ".join(sorted(s.value for s in r.skip_statuses)) or "none"
        lines += [
            "",
            f"## {r.id}",
            "",
            f"**{r.title}** (severity: {r.severity.value}; skipped when status is: {skipped})",
            "",
            f"Why: {r.rationale}",
            "",
            "Sources:",
            "",
        ]
        lines += [f"- [{ref.label()}]({ref.doc.url})" for ref in r.refs]
    return "\n".join(lines) + "\n"


def crosswalk_table() -> str:
    lines = [
        CROSSWALK_BEGIN,
        "",
        "| Check | AI Playbook principle | ATRS section | NIST AI RMF | Other sources |",
        "|---|---|---|---|---|",
    ]
    for r in all_rules():
        principles = ", ".join(
            p.split(":")[0].replace("Principle ", "") for p in _refs(r, "ai-playbook")
        )
        atrs = "; ".join(p for p in _refs(r, "atrs-guidance") if p) or ""
        if any(ref.source == "atrs-scope" for ref in r.refs):
            atrs = "; ".join(x for x in (atrs, "Scope and exemptions policy") if x)
        nist = ", ".join(_refs(r, "nist-ai-rmf"))
        other = "; ".join(
            ref.label()
            for ref in r.refs
            if ref.source not in {"ai-playbook", "atrs-guidance", "atrs-scope", "nist-ai-rmf"}
        )
        lines.append(
            f"| {r.id} {r.title} | {principles or '-'} | {atrs or '-'} | {nist or '-'} | "
            f"{other or '-'} |"
        )
    lines += ["", CROSSWALK_END]
    return "\n".join(lines) + "\n"
